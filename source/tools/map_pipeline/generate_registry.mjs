import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..');
const processedDir = path.join(root, 'assets/maps/processed');
const outFile = path.join(root, 'src/maps_registry.js');

const maps = {};
for (const id of ['foundry', 'glowplant', 'zenith', 'railyard', 'school']) {
  const jsonPath = path.join(processedDir, `${id}.json`);
  if (fs.existsSync(jsonPath)) {
    maps[id] = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    console.log(`Loaded ${id}: ${maps[id].boxes.length} boxes, ${maps[id].spawns.length} spawns`);
  }
}

const jsContent = `/* Central Map Registry for LAN_FPS (Generated by MAPFORGE pipeline) */

export const MAPS_REGISTRY = ${JSON.stringify(maps)};

export function getRegisteredMap(id) {
  return MAPS_REGISTRY[id] || null;
}
`;

fs.writeFileSync(outFile, jsContent);
console.log(`Generated ${outFile} (${(fs.statSync(outFile).size / 1024).toFixed(1)} KB)`);
